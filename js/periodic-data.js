/** بلوک s / p / d / f بر پایه گروه و دسته‌بندی آیوپاک. */
export function blockOf(el) {
  if (el.category === 'lanthanide' || el.category === 'actinide' || !el.group) return 'f';
  if (el.atomicNumber === 2 || el.group <= 2) return 's';
  if (el.group <= 12) return 'd';
  return 'p';
}
