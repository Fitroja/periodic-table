/** کمینه/بیشینه هر ویژگی (در فضای خطی یا لگاریتمی) برای نرمال‌سازی رنگ. */
const RANGES = new Map();
PROPERTIES.forEach((p) => {
  let min = Infinity;
  let max = -Infinity;
  ELEMENTS.forEach((el) => {
    const raw = p.get(el);
    if (raw === null || raw === undefined) return;
    const v = p.scale === 'log' ? Math.log10(Math.max(raw, 1e-20)) : raw;
    if (v < min) min = v;
    if (v > max) max = v;
  });
  RANGES.set(p.key, { min, max });
});

/**
 * موقعیت نسبی یک عنصر روی بازه یک ویژگی.
 * @returns {number|null} عددی بین ۰ و ۱، یا null اگر داده موجود نباشد.
 */
export function normalizedValue(el, propKey) {
  const p = PROPERTY_MAP[propKey];
  if (!p) return null;
  const raw = p.get(el);
  if (raw === null || raw === undefined) return null;
  const { min, max } = RANGES.get(propKey);
  if (!(max > min)) return 0.5;
  const v = p.scale === 'log' ? Math.log10(Math.max(raw, 1e-20)) : raw;
  return (v - min) / (max - min);
}

/** بازه واقعی (نه لگاریتمی) یک ویژگی، برای برچسب دو سر نوار رنگ. */
export function propertyExtent(propKey) {
  const p = PROPERTY_MAP[propKey];
  if (!p) return { min: null, max: null };
  let min = null;
  let max = null;
  ELEMENTS.forEach((el) => {
    const raw = p.get(el);
    if (raw === null || raw === undefined) return;
    if (min === null || raw < min) min = raw;
    if (max === null || raw > max) max = raw;
  });
  return { min, max };
}

/** طیف رنگی نقشه حرارتی: آبی سرد → فیروزه‌ای → کهربایی → سرخ داغ. */
const HEAT_STOPS = [
  [0.0, [12, 32, 92]],
  [0.25, [6, 148, 200]],
  [0.5, [16, 200, 140]],
  [0.72, [240, 186, 48]],
  [1.0, [244, 63, 94]],
];

/** رنگ نقشه حرارتی برای مقدار نرمال‌شده t (۰ تا ۱) به صورت «#rrggbb». */
export function heatColor(t) {
  const x = Math.min(1, Math.max(0, t));
  let a = HEAT_STOPS[0];
  let b = HEAT_STOPS[HEAT_STOPS.length - 1];
  for (let i = 0; i < HEAT_STOPS.length - 1; i += 1) {
    if (x >= HEAT_STOPS[i][0] && x <= HEAT_STOPS[i + 1][0]) {
      a = HEAT_STOPS[i];
      b = HEAT_STOPS[i + 1];
      break;
    }
  }
  const span = b[0] - a[0] || 1;
  const k = (x - a[0]) / span;
  const ch = (i) => Math.round(a[1][i] + (b[1][i] - a[1][i]) * k);
  return `#${[ch(0), ch(1), ch(2)].map((n) => n.toString(16).padStart(2, '0')).join('')}`;
}

/** رشته CSS گرادیان طیف حرارتی (برای نوار راهنمای رنگ). */
export const HEAT_GRADIENT_CSS = `linear-gradient(to right, ${HEAT_STOPS.map(
  (s) => `${heatColor(s[0])} ${(s[0] * 100).toFixed(0)}%`
).join(', ')})`;

/** تبدیل ارقام لاتین به فارسی برای نمایش در رابط کاربری. */
export function toFaDigits(value) {
  return String(value).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);
}

